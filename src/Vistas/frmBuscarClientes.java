    private void jList1ValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jList1ValueChanged
        
        String seleccion = String.valueOf(jList1.getSelectedValue());
        
        for (Map.Entry<Long, Contacto> aux : Principal.directorio.directorio.entrySet()) {
            Long tel = aux.getKey();
            Contacto contacto = aux.getValue();
            
            
            if (seleccion.equals(String.valueOf(tel))) {
                DNItxtfield.setText(String.valueOf(contacto.getDni()));
                NombreTxtfield.setText(contacto.getNombre());
                ApellidoTxtfield.setText(contacto.getApellido());
                ciudadTXT.setText(contacto.getCiudad());
                DomicilioTxtfield.setText(contacto.getDireccion());
                TelefonoTxtField.setText(String.valueOf(contacto));
            } 
            
            
            
        }

        
    }//GEN-LAST:event_jList1ValueChanged


